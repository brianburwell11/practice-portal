/**
 * Emit the role/capability seed migration from `server/db/capabilities.ts`, so
 * the SQL can't drift from the typed catalog.
 *
 * Usage:
 *   npx tsx scripts/gen-seed-migration.ts               # write the file
 *   npx tsx scripts/gen-seed-migration.ts --check       # fail if stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { CAPABILITIES, ROLES } from '../server/db/capabilities';

const OUT = path.join(
  import.meta.dirname,
  '../server/db/migrations/0002_seed_roles_and_capabilities.sql',
);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

function build(): string {
  const lines: string[] = [
    '-- Generated by scripts/gen-seed-migration.ts from server/db/capabilities.ts.',
    '-- Do not hand-edit: change the catalog there and re-run `npm run db:seed:gen`.',
    '--',
    '-- Idempotent so it is safe to re-apply. After this lands, re-cutting a role',
    '-- bundle is an INSERT/DELETE on role_capability — not a migration, not a deploy.',
    '',
    'INSERT INTO "capability" ("key", "description") VALUES',
  ];

  const caps = Object.entries(CAPABILITIES);
  lines.push(caps.map(([k, d]) => `  (${q(k)}, ${q(d)})`).join(',\n'));
  lines.push('ON CONFLICT ("key") DO UPDATE SET "description" = EXCLUDED."description";');
  lines.push('--> statement-breakpoint');
  lines.push('');
  lines.push('INSERT INTO "role" ("key", "label", "sort_order", "membership_eligible") VALUES');
  lines.push(
    ROLES.map((r) => `  (${q(r.key)}, ${q(r.label)}, ${r.sortOrder}, ${r.membershipEligible})`).join(',\n'),
  );
  lines.push(
    'ON CONFLICT ("key") DO UPDATE SET '
    + '"label" = EXCLUDED."label", '
    + '"sort_order" = EXCLUDED."sort_order", '
    + '"membership_eligible" = EXCLUDED."membership_eligible";',
  );
  lines.push('--> statement-breakpoint');
  lines.push('');
  lines.push('INSERT INTO "role_capability" ("role_key", "capability_key") VALUES');
  lines.push(
    ROLES.flatMap((r) => r.capabilities.map((c) => `  (${q(r.key)}, ${q(c)})`)).join(',\n'),
  );
  lines.push('ON CONFLICT DO NOTHING;');
  lines.push('');

  return lines.join('\n');
}

const sql = build();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : '';
  if (current !== sql) {
    console.error(
      `${path.relative(process.cwd(), OUT)} is stale.\n`
      + 'Run `npm run db:seed:gen` and commit the result.',
    );
    process.exit(1);
  }
  console.log('seed migration is up to date');
} else {
  fs.writeFileSync(OUT, sql);
  const pairs = ROLES.reduce((n, r) => n + r.capabilities.length, 0);
  console.log(
    `wrote ${path.relative(process.cwd(), OUT)} — `
    + `${Object.keys(CAPABILITIES).length} capabilities, ${ROLES.length} roles, ${pairs} grants`,
  );
}
